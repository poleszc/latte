/// ===================== LEXER ======================
fn generate_lexer_tests() -> io::Result<()> {
    let out_dir = env::var("OUT_DIR").expect("OUT_DIR env variable not set");

    let mut parsing_file = fs::File::create(Path::new(&out_dir).join("lexer_tests.rs"))?;
    writeln!(&mut parsing_file, "/* AUTOGENERATED PARSING TESTS */\n")?;

    let test_dir = Path::new("tests").join("bad").join("lexical");
    for entry in fs::read_dir(&test_dir)? {
        let entry = entry?;
        let path = entry.path();
        if path.is_file() && path.extension().and_then(|ext| ext.to_str()) == Some("lat") {
            let file_stem = path.file_stem().unwrap().to_str().unwrap();
            let test_name = file_stem.replace(|c: char| !c.is_alphanumeric(), "_");

            writeln!(
                &mut parsing_file,
                "#[test]\nfn parsing_pass_{}() {{\n    assert_parsing_fails(r\"{}\");\n}}\n",
                test_name,
                path.display(),
            )?;
        }
    }
    println!("cargo:rerun-if-changed=tests/bad/lexical");
    Ok(())
}

