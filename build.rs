use std::{
    env, fs,
    io::{self, Write},
    path::Path,
};

fn main() {
    println!("cargo:rerun-if-changed=src/latte.lalrpop");
    lalrpop::process_root().unwrap();
    generate_basic_parsing_tests().unwrap();
    generate_extensions_parsing_tests().unwrap();
}

fn generate_basic_parsing_tests() -> io::Result<()> {
    let out_dir = env::var("OUT_DIR").expect("OUT_DIR env variable not set");

    let mut parsing_file = fs::File::create(Path::new(&out_dir).join("basic_parsing_tests.rs"))?;
    writeln!(&mut parsing_file, "/* AUTOGENERATED PARSING TESTS */\n")?;

    // Generate pass tests.
    let test_dir = Path::new("tests").join("good");
    for entry in fs::read_dir(&test_dir)? {
        let entry = entry?;
        let path = entry.path();

        if path.is_file() && path.extension().and_then(|ext| ext.to_str()) == Some("lat") {
            let file_stem = path.file_stem().unwrap().to_str().unwrap();
            let test_name = file_stem.replace(|c: char| !c.is_alphanumeric(), "_");

            writeln!(
                &mut parsing_file,
                "#[test]\nfn parsing_pass_{}() {{\n    assert_parsing_succeeds(r\"{}\");\n}}\n",
                test_name,
                path.display(),
            )?;
        }
    }
    println!("cargo:rerun-if-changed=tests/good");
    Ok(())
}

fn generate_extensions_parsing_tests() -> io::Result<()> {
    let out_dir = env::var("OUT_DIR").expect("OUT_DIR env variable not set");

    let mut parsing_file =
        fs::File::create(Path::new(&out_dir).join("extensions_parsing_tests.rs"))?;
    writeln!(&mut parsing_file, "/* AUTOGENERATED PARSING TESTS */\n")?;

    // Generate pass tests.
    let test_dir = Path::new("tests").join("extensions");
    for entry in fs::read_dir(&test_dir)? {
        let entry = entry?;
        let path = entry.path();
        if path.is_dir() {
            for entry in fs::read_dir(path)? {
                let entry = entry?;
                let path = entry.path();
                if path.is_file() && path.extension().and_then(|ext| ext.to_str()) == Some("lat") {
                    let file_stem = path.file_stem().unwrap().to_str().unwrap();
                    let test_name = file_stem.replace(|c: char| !c.is_alphanumeric(), "_");

                    writeln!(
                        &mut parsing_file,
                        "#[test]\nfn parsing_pass_{}() {{\n    assert_parsing_succeeds(r\"{}\");\n}}\n",
                        test_name,
                        path.display(),
                    )?;
                }
            }
        }
    }
    println!("cargo:rerun-if-changed=tests/extensions");
    Ok(())
}

fn _generate_integration_tests() -> io::Result<()> {
    let out_dir = env::var("OUT_DIR").expect("OUT_DIR env variable not set");

    let mut parsing_file = fs::File::create(Path::new(&out_dir).join("parsing_tests.rs"))?;
    let mut semantic_file = fs::File::create(Path::new(&out_dir).join("semantic_tests.rs"))?;
    let mut integration_file = fs::File::create(Path::new(&out_dir).join("integration_tests.rs"))?;

    writeln!(&mut parsing_file, "/* AUTOGENERATED PARSING TESTS */\n")?;
    writeln!(&mut semantic_file, "/* AUTOGENERATED SEMANTIC TESTS */\n")?;
    writeln!(
        &mut integration_file,
        "/* AUTOGENERATED INTEGRATION TESTS */\n"
    )?;

    let test_dir = Path::new("tests").join("in");
    for entry in fs::read_dir(&test_dir)? {
        let entry = entry?;
        let path = entry.path();

        if path.is_file() && path.extension().and_then(|ext| ext.to_str()) == Some("ins") {
            let file_stem = path.file_stem().unwrap().to_str().unwrap();
            let test_name = file_stem.replace(|c: char| !c.is_alphanumeric(), "_");

            // Parsing tests.
            if file_stem.starts_with("bad_") {
                writeln!(
                    &mut parsing_file,
                    "#[test]\nfn test_fail_{}() {{\n    assert_parsing_fails(r\"{}\");\n}}\n",
                    test_name,
                    path.display(),
                )?;
            } else {
                writeln!(
                    &mut parsing_file,
                    "#[test]\nfn test_pass_{}() {{\n    assert_parsing_succeeds(r\"{}\");\n}}\n",
                    test_name,
                    path.display(),
                )?;
            }

            // Semantic Error.
            if file_stem.starts_with("error_") {
                writeln!(
                    &mut semantic_file,
                    "#[test]\nfn test_fail_{}() {{\n    assert_compilation_fails(r\"{}\");\n}}\n",
                    test_name,
                    path.display(),
                )?;
            }

            // Integration tests.
            if !file_stem.starts_with("bad_") && !file_stem.starts_with("error_") {
                let out_path = Path::new("tests")
                    .join("out")
                    .join(format!("{}.output", file_stem));

                if out_path.exists() {
                    writeln!(
                        &mut integration_file,
                        "#[test]\nfn itest_jvm_{}() {{\n    run_itest(r\"{}\", r\"{}\", Backend::Jvm);\n}}\n",
                        test_name,
                        path.display(),
                        out_path.display()
                    )?;

                    writeln!(
                        &mut integration_file,
                        "#[test]\nfn itest_llvm_{}() {{\n    run_itest(r\"{}\", r\"{}\", Backend::Llvm);\n}}\n",
                        test_name,
                        path.display(),
                        out_path.display()
                    )?;
                }
            }
        }
    }
    println!("cargo:rerun-if-changed=tests/in");
    println!("cargo:rerun-if-changed=tests/out");
    Ok(())
}
